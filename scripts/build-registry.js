#!/usr/bin/env node
'use strict';
/*
 * site/data/asset-registry.json  →  site/data/asset-registry.js
 * The JSON is the source of truth (people, AI agents or a CMS edit it). The .js
 * copy only exists so the static site also works when opened from disk (file://
 * cannot fetch JSON). When served over http(s) the site reads the JSON directly,
 * or a remote registry if MOSPORT_CONFIG.assetRegistryUrl is set.
 *
 *   node scripts/build-registry.js          write the .js
 *   node scripts/build-registry.js --check  fail if the .js is stale or the JSON invalid
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const R = require('../site/js/assets/registry.js');

const SITE = path.join(__dirname, '..', 'site');
const SRC = path.join(SITE, 'data', 'asset-registry.json');
const OUT = path.join(SITE, 'data', 'asset-registry.js');

const reg = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const errs = R.validate(reg);

/* Every referenced file exists and matches its recorded hash. */
const versions = [];
for (const [id, s] of Object.entries(reg.slots || {})) (s.versions || []).forEach((v) => versions.push([id, v]));
for (const [id, s] of Object.entries(reg.logos || {})) (s.versions || []).forEach((v) => versions.push([id, v]));
for (const [code, s] of Object.entries((reg.teamLogos || {}).entries || {})) (s.versions || []).forEach((v) => versions.push(['team:' + code, v]));
for (const [id, v] of versions) {
  for (const f of [v.file, v.darkFile].filter(Boolean)) {
    const p = path.join(SITE, f);
    if (!fs.existsSync(p)) { errs.push(`${id}/${v.id}: file missing ${f}`); continue; }
    const slotDef = (reg.slots || {})[id] || (reg.logos || {})[id] || (reg.teamLogos || {});
    const max = slotDef.deliver && slotDef.deliver.maxBytes;
    if (max && v.status !== 'PLACEHOLDER' && fs.statSync(p).size > max) errs.push(`${id}/${v.id}: ${f} is ${fs.statSync(p).size} bytes, over ${max}`);
    if (f === v.file) {
      const h = crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
      if (h !== v.sha256) errs.push(`${id}/${v.id}: sha256 mismatch for ${f}`);
    }
  }
}

const body = '/* GENERATED by scripts/build-registry.js from asset-registry.json. Do not edit. */\n' +
  'window.MOSPORT_ASSET_REGISTRY = ' + JSON.stringify(reg, null, 2) + ';\n';

if (errs.length) { console.error('Asset registry invalid:\n- ' + errs.join('\n- ')); process.exit(1); }
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.error('site/data/asset-registry.js is stale: run npm run registry:build'); process.exit(1); }
  console.log(`Asset registry OK (${Object.keys(reg.slots).length} art slots, ${versions.length} versions)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log('Wrote ' + path.relative(process.cwd(), OUT));
}
